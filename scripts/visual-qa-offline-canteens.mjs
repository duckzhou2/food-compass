import { mkdir, readFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { chromium } from "playwright";

const projectRoot = process.cwd();
const offlineUrl = pathToFileURL(path.join(projectRoot, "offline", "食物罗盘-离线版.html")).href;
const outputDirectory = path.join(projectRoot, "artifacts", "visual-qa-offline-canteens");
const catalog = JSON.parse(await readFile(path.join(projectRoot, "data", "canteens", "catalog.json"), "utf8"));
const viewports = [{ name: "360", width: 360, height: 800 }, { name: "390", width: 390, height: 844 }, { name: "768", width: 768, height: 900 }, { name: "1440", width: 1440, height: 1000 }];
await mkdir(outputDirectory, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const results = [];
try {
  for (const viewport of viewports) {
    const page = await browser.newPage({ viewport });
    const consoleErrors = [], externalRequests = [];
    page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });
    page.on("request", (request) => { if (!request.url().startsWith("file:") && !request.url().startsWith("data:")) externalRequests.push(request.url()); });
    await page.goto(`${offlineUrl}#canteens`, { waitUntil: "load" });
    await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); location.reload(); });
    await page.waitForFunction(() => document.querySelector("#canteens")?.classList.contains("active"));
    const canteenCards = await page.locator("#canteenCards .canteen-card").count();
    await page.locator("#canteenFilters").evaluate((element) => { element.open = true; });
    await page.locator("[data-filter-kind='canteens'][data-filter-value='canteen-shaoyuan']").click();
    const linkedFloorIds = await page.locator("[data-filter-kind='floors'][data-filter-value]:not([data-filter-value=''])").evaluateAll((buttons) => buttons.map((button) => button.getAttribute("data-filter-value")));
    const linkedWindowIds = await page.locator("[data-filter-kind='windows'][data-filter-value]:not([data-filter-value=''])").evaluateAll((buttons) => buttons.map((button) => button.getAttribute("data-filter-value")));
    const hierarchyLinked = linkedFloorIds.length > 0 && linkedFloorIds.every((id) => id?.startsWith("floor-shaoyuan-")) && linkedWindowIds.length > 0 && linkedWindowIds.every((id) => id?.startsWith("window-shaoyuan-"));
    await page.locator("[data-filter-kind='canteens'][data-filter-value='']").click();
    await page.locator("[data-filter-kind='canteens'][data-filter-value='canteen-xueyi']").click();
    await page.locator("[data-canteen-mode='recommend']").click();
    await page.evaluate(() => { Math.random = () => 0.999999; });
    await page.locator("#canteenDraw").click();
    await page.locator("[data-rec-action='confirm']").click();
    await page.locator("#canteenDraw").click();
    const pendingWindowReached = (await page.locator("#canteenRecResult h3").textContent())?.trim() === "窗口待确认（其他菜品）";
    await page.locator("[data-rec-action='confirm']").click();
    const pendingDishCount = Number(await page.locator("#canteenStageCount").textContent());
    await page.reload({ waitUntil: "load" });
    await page.waitForFunction(() => document.querySelector("#canteens")?.classList.contains("active"));
    await page.getByLabel("全局搜索").fill("襄阳牛肉面");
    await page.locator("[data-s-type='菜品']").first().click();
    const searchDetail = (await page.locator("#canteenModalBody h2").textContent())?.trim();
    await page.getByRole("button", { name: "关闭" }).click();
    await page.getByRole("button", { name: "菜品浏览" }).click();
    const dishCards = await page.locator("#canteenCards .canteen-card").count();
    await page.locator("[data-cf-kind='dishes']").first().click();
    const favorites = await page.evaluate(() => JSON.parse(localStorage.getItem("foodCompass.canteen.favorites") || "{}").dishes?.length ?? 0);
    await page.getByRole("button", { name: "转盘帮我选" }).click();
    await page.locator("#canteenDraw").click();
    await page.locator("[data-rec-action='confirm']").click();
    await page.locator("#canteenDraw").click();
    await page.locator("[data-rec-action='confirm']").click();
    await page.locator("#canteenDraw").click();
    const recommendation = (await page.locator("#canteenRecResult h3").textContent())?.trim();
    await page.locator("[data-rec-action='confirm']").click();
    const selected = await page.evaluate(() => JSON.parse(localStorage.getItem("foodCompass.canteen.recentSelections") || "[]").length);
    await page.reload({ waitUntil: "load" });
    const persisted = await page.evaluate(() => ({ favorite: JSON.parse(localStorage.getItem("foodCompass.canteen.favorites") || "{}").dishes?.length ?? 0, selected: JSON.parse(localStorage.getItem("foodCompass.canteen.recentSelections") || "[]").length }));
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth + 1);
    await page.screenshot({ path: path.join(outputDirectory, `canteens-${viewport.name}.png`), fullPage: true });
    results.push({ viewport: viewport.name, canteenCards, hierarchyLinked, pendingWindowReached, pendingDishCount, dishCards, searchDetail, favorites, recommendation, selected, persisted, overflow, consoleErrors, externalRequests });
    await page.close();
  }
} finally { await browser.close(); }
const dataValid = catalog.canteens.filter((item) => !item.isServicePoint).length === 14 && catalog.dishes.length === 650 && catalog.dishes.flatMap((dish) => dish.skus).length === 514;
const failed = !dataValid || results.some((result) => result.canteenCards !== 14 || !result.hierarchyLinked || !result.pendingWindowReached || result.pendingDishCount !== 65 || result.dishCards < 1 || result.searchDetail !== "襄阳牛肉面" || result.favorites !== 1 || !result.recommendation || result.selected !== 1 || result.persisted.favorite !== 1 || result.persisted.selected !== 1 || result.overflow || result.consoleErrors.length || result.externalRequests.length);
console.log(JSON.stringify({ dataValid, results }, null, 2));
if (failed) throw new Error("离线北大食堂模块浏览器验收未通过");
